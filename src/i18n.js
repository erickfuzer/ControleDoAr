export const T = STR[lang];

/// Rótulo de um valor da API; valores desconhecidos de outros modelos aparecem como vieram.
export function label(group, value) {
  return (T[group] && T[group][value]) || value || "--";
}

/// ["a", "b", "c"] → "A, b e c"
export function listText(items) {
  if (items.length === 0) return "";
  const text = items.length === 1 ? items[0] : `${items.slice(0, -1).join(", ")} ${T.and} ${items.at(-1)}`;
  return text[0].toUpperCase() + text.slice(1);
}

/// Preenche os elementos com data-i18n / data-i18n-placeholder.
export function applyStatic(root = document) {
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = T[el.dataset.i18n];
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = T[el.dataset.i18nPlaceholder];
}
